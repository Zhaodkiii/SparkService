def doctors_with_departments() -> list[dict[str, str]]:
    seen: set[str] = set()
    items = []
    for name, title, room, introduction in PUBLIC_DOCTORS:
        if name in seen:
            continue
        seen.add(name)
        items.append(
            {
                "name": name,
                "title": title,
                "room": room,
                "introduction": introduction,
                "department_code": _infer_department(title, introduction, room),
            }
        )
    return items
