class HospitalCareError(APIError):
    def __init__(self, error_code: str, *, details: dict[str, Any] | None = None, status_code: int | None = None):
        payload = {"error_code": error_code, **(details or {})}
        super().__init__(
            error_code,
            code=ERROR_INT.get(error_code, -1),
            status_code=status_code or ERROR_HTTP.get(error_code, 400),
            details=payload,
        )
        self.error_code = error_code
